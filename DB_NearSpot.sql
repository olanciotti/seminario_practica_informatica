-- BASE DE DATOS NEARSPOT

--Elimina la DB en caso de que exista
DROP DATABASE IF EXISTS nearspot;

--Crea la DB
CREATE DATABASE nearspot

USE nearspot;

-- TABLA ROL
CREATE TABLE rol (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY,
    nombre VARCHAR2(45) NOT NULL,
    CONSTRAINT pk_rol PRIMARY KEY (id)
);


-- TABLA TIPO_ACTOR
CREATE TABLE tipo_actor (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY,
    nombre VARCHAR2(45) NOT NULL,
    CONSTRAINT pk_tipo_actor PRIMARY KEY (id)
);


-- TABLA RUBRO
CREATE TABLE rubro (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY,
    nombre VARCHAR2(45) NOT NULL,
    descripcion VARCHAR2(255),
    estado VARCHAR2(45) DEFAULT 'ACTIVO' NOT NULL,
    CONSTRAINT pk_rubro PRIMARY KEY (id)
);


-- TABLA ZONA
CREATE TABLE zona (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY,
    nombre VARCHAR2(45) NOT NULL,
    CONSTRAINT pk_zona PRIMARY KEY (id)
);


-- TABLA USUARIO
CREATE TABLE usuario (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY,
    nombre VARCHAR2(45) NOT NULL,
    apellido VARCHAR2(45) NOT NULL,
    email VARCHAR2(150) NOT NULL,
    password VARCHAR2(255) NOT NULL,
    estado VARCHAR2(45) DEFAULT 'ACTIVO' NOT NULL,
    rol_id NUMBER NOT NULL,
    CONSTRAINT pk_usuario PRIMARY KEY (id),
    CONSTRAINT uq_usuario_email UNIQUE (email),
    CONSTRAINT fk_usuario_rol FOREIGN KEY (rol_id) REFERENCES rol(id)
);


-- TABLA UBICACION
CREATE TABLE ubicacion (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY,
    direccion VARCHAR2(255),
    localidad VARCHAR2(100) NOT NULL,
    provincia VARCHAR2(100) NOT NULL,
    latitud NUMBER(9,6),
    longitud NUMBER(10,6),
    zona_id NUMBER,

    CONSTRAINT pk_ubicacion PRIMARY KEY (id),
    CONSTRAINT fk_ubicacion_zona FOREIGN KEY (zona_id) REFERENCES zona(id)
);


-- TABLA PRESTADOR
CREATE TABLE prestador (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY,
    nombre VARCHAR2(100) NOT NULL,
    descripcion VARCHAR2(500),
    telefono VARCHAR2(30),
    email VARCHAR2(150),
    sitio_web VARCHAR2(255),
    instagram VARCHAR2(100),
    horario_atencion TIMESTAMP,
    estado VARCHAR2(45) DEFAULT 'ACTIVO' NOT NULL,
    fecha_alta TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    tipo_actor_id NUMBER NOT NULL,
    usuario_id NUMBER NOT NULL,
    ubicacion_id NUMBER,
    rubro_id NUMBER NOT NULL,

    CONSTRAINT pk_prestador PRIMARY KEY (id),
    CONSTRAINT fk_prestador_tipo_actor FOREIGN KEY (tipo_actor_id) REFERENCES tipo_actor(id),
    CONSTRAINT fk_prestador_usuario FOREIGN KEY (usuario_id) REFERENCES usuario(id),
    CONSTRAINT fk_prestador_ubicacion FOREIGN KEY (ubicacion_id) REFERENCES ubicacion(id),
    CONSTRAINT fk_prestador_rubro FOREIGN KEY (rubro_id) REFERENCES rubro(id)
);


-- TABLA PRESTACION
CREATE TABLE prestacion (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY,
    nombre VARCHAR2(100) NOT NULL,
    descripcion VARCHAR2(500),
    tipo VARCHAR2(45) NOT NULL,
    prestador_id NUMBER NOT NULL,

    CONSTRAINT pk_prestacion PRIMARY KEY (id),
    CONSTRAINT fk_prestacion_prestador FOREIGN KEY (prestador_id) REFERENCES prestador(id)
);


-- TABLA RESEÑA
CREATE TABLE reseña (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY,
    contenido VARCHAR2(1000) NOT NULL,
    fecha TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    estado VARCHAR2(45) DEFAULT 'ACTIVA' NOT NULL,
    usuario_id NUMBER NOT NULL,
    prestador_id NUMBER NOT NULL,

    CONSTRAINT pk_resena PRIMARY KEY (id),
    CONSTRAINT fk_resena_usuario FOREIGN KEY (usuario_id) REFERENCES usuario(id),
    CONSTRAINT fk_resena_prestador FOREIGN KEY (prestador_id) REFERENCES prestador(id)
);


-- TABLA CALIFICACION
CREATE TABLE calificacion (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY,
    valor NUMBER(2) NOT NULL,
    fecha TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    estado VARCHAR2(45) DEFAULT 'ACTIVA' NOT NULL,
    usuario_id NUMBER NOT NULL,
    prestador_id NUMBER NOT NULL,

    CONSTRAINT pk_calificacion PRIMARY KEY (id),
    CONSTRAINT chk_calificacion_valor CHECK (valor BETWEEN 1 AND 5),
    CONSTRAINT fk_calificacion_usuario FOREIGN KEY (usuario_id) REFERENCES usuario(id),
    CONSTRAINT fk_calificacion_prestador FOREIGN KEY (prestador_id) REFERENCES prestador(id),
    CONSTRAINT uq_calificacion_usuario_prestador UNIQUE (usuario_id, prestador_id)
);
